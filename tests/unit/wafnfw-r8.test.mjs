function mockSocket(kind, delay = 0) {
  const s = new EventEmitter();
  s.destroy = () => {};
  s.end = () => {};
  setTimeout(() => {
    if (kind === 'connect') s.emit('connect');
    else if (kind === 'silent') {}
    else s.emit('error', Object.assign(new Error(kind), { code: kind }));
  }, delay);
  return s;
}

