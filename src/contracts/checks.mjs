export function buildProbeProfile({
  kind,
  max_requests = 1,
  timeout_ms = 5000,
  marker,
  scenario,
  scenario_family,
  marker_type,
  expected_action,
  nonce_hash_only,
  collect,
  service_port,
  payload_profile,
  expected_response_shape,
  http_method,
  dns_qtype,
  dns_transport,
  oversize_header_bytes,
  marker_class,
  evasion_transform,
  settings_assertion,
  entry_path_scenario,
  permitted_baseline,
  ...capabilityFields
} = {}) {
  if (!ALLOWED_PROBE_KINDS.has(kind)) {
    throw new Error(`invalid probe profile kind: ${kind}`);
  }
  const kindCap = maxProbeRequestsForKind(kind);
  const cappedRequests = Math.min(
    Math.max(1, Number(max_requests) || 1),
    kindCap,
  );
  const cappedTimeout = Math.min(
    Math.max(100, Number(timeout_ms) || MAX_PROBE_PROFILE_TIMEOUT_MS),
    MAX_PROBE_PROFILE_TIMEOUT_MS,
  );
  const profile = {
    kind,
    max_requests: cappedRequests,
    timeout_ms: cappedTimeout,
  };
  if (marker) profile.marker = String(marker).slice(0, 128);
  if (kind === 'http_head') profile.method = 'HEAD';
  // An explicit customer target.port overrides this canonical service port at execution time.
  if (Number.isInteger(service_port) && service_port >= 1 && service_port <= 65535) {
    profile.service_port = service_port;
  }
  if (typeof payload_profile === 'string' && ALLOWED_PAYLOAD_PROFILE_SET.has(payload_profile)) {
    profile.payload_profile = payload_profile;
  }
  if (
    typeof expected_response_shape === 'string'
    && ALLOWED_EXPECTED_RESPONSE_SHAPE_SET.has(expected_response_shape)
  ) {
    profile.expected_response_shape = expected_response_shape;
  }
  if (
    HTTP_METHOD_PROFILE_KINDS.has(kind)
    && typeof http_method === 'string'
    && ALLOWED_PROBE_HTTP_METHOD_SET.has(http_method)
  ) {
    if (http_method === 'POST' && nonce_hash_only !== true) {
      throw new Error('POST probe profiles require nonce_hash_only: true');
    }
    profile.http_method = http_method;
  }
  if (kind === 'dns_wire_query' && typeof dns_qtype === 'string' && ALLOWED_DNS_QTYPE_SET.has(dns_qtype)) {
    profile.dns_qtype = dns_qtype;
  }
  if (
    kind === 'dns_wire_query'
    && typeof dns_transport === 'string'
    && ALLOWED_DNS_TRANSPORT_SET.has(dns_transport)
  ) {
    profile.dns_transport = dns_transport;
  }
  if (
    kind === 'header_size_probe'
    && Number.isInteger(oversize_header_bytes)
    && oversize_header_bytes >= 1024
    && oversize_header_bytes <= 16384
  ) {
    profile.oversize_header_bytes = oversize_header_bytes;
  }
  if (kind === 'ops_readiness' && typeof scenario === 'string' && ALLOWED_OPS_READINESS_SCENARIOS.has(scenario)) {
    profile.scenario = scenario;
  }
  if (
    MARKER_CLASS_PROFILE_KINDS.has(kind)
    && typeof marker_class === 'string'
    && SAFE_MARKER_TOKEN.test(marker_class)
  ) {
    profile.marker_class = marker_class;
  }
  if (
    kind === 'waf_evasion_marker_probe'
    && typeof evasion_transform === 'string'
    && SAFE_MARKER_TOKEN.test(evasion_transform)
  ) {
    profile.evasion_transform = evasion_transform;
  }
  if (
    ENTRY_PATH_SCENARIO_PROFILE_KINDS.has(kind)
    && typeof entry_path_scenario === 'string'
    && ENTRY_PATH_PROFILE_SCENARIOS.has(entry_path_scenario)
  ) {
    profile.entry_path_scenario = entry_path_scenario;
    if (kind === 'waf_evasion_marker_probe') profile.permitted_baseline = true;
  }
  if (kind === 'waf_evasion_marker_probe' && permitted_baseline === true) profile.permitted_baseline = true;
  if (
    kind === 'http2_frame_probe'
    && typeof settings_assertion === 'string'
    && ALLOWED_HTTP2_SETTINGS_ASSERTIONS.has(settings_assertion)
  ) {
    profile.settings_assertion = settings_assertion;
  }
  applyWafSafeProbeMetadata(profile, {
    scenario_family,
    marker_type,
    expected_action,
    nonce_hash_only,
    collect,
  });
  for (const key of CAPABILITY_PROFILE_PASSTHROUGH_KEYS) {
    if (capabilityFields[key] == null) continue;
    if (key === 'graphql_path' || key === 'grpc_path' || key === 'probe_path') {
      const path = normalizeProbeHttpPath(capabilityFields[key]);
      if (path) profile[key] = path;
      continue;
    }
    profile[key] = capabilityFields[key];
  }
  // Signed outside-in execution has a static, pre-reserved HTTP plan. Keep redirect expansion
  // disabled even when a legacy catalog or caller override requests it.
  if (kind === 'outside_in_waf_scan') profile.follow_redirects = false;
  return profile;
}

